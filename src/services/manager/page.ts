import type { Response } from 'express';
import { base, menus } from '../../config/manager.js';
import { managerResourceLocals } from '../../config/manager/resources.js';

export type RenderPage = (res: Response, data: Record<string, unknown>) => unknown;

export function createPageRenderer(authEnabled: boolean, databaseReady: boolean): RenderPage {
  return (res: Response, data: Record<string, unknown>) =>
    res.render('manager/page', {
      ...managerResourceLocals,
      base,
      menus,
      authEnabled,
      databaseReady: databaseReady,
      userName: '',
      loginError: '',
      users: [],
      labelPage: null,
      libraryPage: null,
      outputPage: null,
      documentPage: null,
      labelPermissions: res.locals.labelPermissions ?? null,
      userCount: 0,
      searchId: '',
      searchName: '',
      userFilters: null,
      catalog: null,
      detail: null,
      systemTable: null,
      systemMenu: res.locals.systemMenu ?? [],
      systemPermissionMap: res.locals.systemPermissionMap ?? null,
      settings: null,
      adminForm: null,
      taskPage: null,
      mailPage: null,
      mailTemplatePage: null,
      mailLogPage: null,
      userAccountLogPage: null,
      directPage: null,
      webhookPage: null,
      systemDataPage: null,
      systemLocksPage: null,
      systemMaintenancePage: null,
      systemUploadsPage: null,
      systemLicensePage: null,
      systemLogsPage: null,
      systemFilesPage: null,
      cloudCredentialsPage: null,
      irfdPage: null,
      mbCloudPage: null,
      meIdPage: null,
      iwproPage: null,
      edgeOcrPage: null,
      userPage: null,
      systemGroupPage: null,
      devicePage: null,
      csrfToken: res.locals.csrfToken ?? '',
      loggedOut: false,
      ...data,
    });
}
